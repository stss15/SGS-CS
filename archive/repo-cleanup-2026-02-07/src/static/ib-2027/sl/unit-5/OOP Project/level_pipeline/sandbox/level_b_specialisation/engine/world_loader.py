"""
World Loader - Loads and manages game world content from JSON files.

Engine-owned. Students do NOT edit this file.
"""

import json
import os
from pathlib import Path


class WorldLoader:
    """Loads and provides access to world content (rooms, items, NPCs, encounters)."""
    
    def __init__(self, content_path: str = None):
        """
        Initialize the world loader.
        
        Args:
            content_path: Path to the content directory. Defaults to engine/content/.
        """
        if content_path is None:
            # Default to engine/content relative to this file
            content_path = Path(__file__).parent / "content"
        else:
            content_path = Path(content_path)
        
        self.content_path = content_path
        self.rooms = {}
        self.items = {}
        self.npcs = {}
        self.encounters = {}
        self.puzzles = {}
        
        self._load_all()
    
    def _load_json(self, filename: str) -> dict:
        """Load a JSON file from the content directory."""
        filepath = self.content_path / filename
        if not filepath.exists():
            print(f"Warning: Content file not found: {filepath}")
            return {}
        
        with open(filepath, 'r', encoding='utf-8') as f:
            return json.load(f)
    
    def _load_all(self):
        """Load all content files."""
        # Load rooms
        rooms_data = self._load_json("rooms.json")
        if "rooms" in rooms_data:
            for room in rooms_data["rooms"]:
                self.rooms[room["id"]] = room
        
        # Load items
        items_data = self._load_json("items.json")
        if "items" in items_data:
            for item in items_data["items"]:
                self.items[item["id"]] = item
        
        # Load NPCs
        npcs_data = self._load_json("npcs.json")
        if "npcs" in npcs_data:
            for npc in npcs_data["npcs"]:
                self.npcs[npc["id"]] = npc
        
        # Load encounters
        encounters_data = self._load_json("encounters.json")
        if "encounters" in encounters_data:
            for encounter in encounters_data["encounters"]:
                self.encounters[encounter["id"]] = encounter
    
    def get_room(self, room_id: str) -> dict:
        """Get room data by ID."""
        return self.rooms.get(room_id)
    
    def get_item(self, item_id: str) -> dict:
        """Get item data by ID."""
        return self.items.get(item_id)
    
    def get_npc(self, npc_id: str) -> dict:
        """Get NPC data by ID."""
        return self.npcs.get(npc_id)
    
    def get_encounter(self, encounter_id: str) -> dict:
        """Get encounter data by ID."""
        return self.encounters.get(encounter_id)
    
    def get_room_items(self, room_id: str) -> list:
        """Get list of items currently in a room."""
        room = self.get_room(room_id)
        if room and "items" in room:
            return room["items"][:]
        return []
    
    def get_room_npcs(self, room_id: str) -> list:
        """Get list of NPCs in a room."""
        room = self.get_room(room_id)
        if room and "npcs" in room:
            return room["npcs"][:]
        return []
    
    def get_start_room(self) -> str:
        """Get the starting room ID."""
        return "airlock"
    
    def get_room_exits(self, room_id: str) -> dict:
        """Get available exits from a room."""
        room = self.get_room(room_id)
        if room and "exits" in room:
            return room["exits"].copy()
        return {}
