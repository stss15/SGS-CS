import time
import sys
import random


# ============================================================================
# TEXT EFFECTS
# ============================================================================

def type_text(text, delay=0.02):
    """Print text with typewriter effect."""
    for char in text:
        print(char, end='', flush=True)
        time.sleep(delay)
    print()


def type_text_slow(text, delay=0.04):
    """Slower typewriter for dramatic moments."""
    for char in text:
        print(char, end='', flush=True)
        time.sleep(delay)
    print()


def type_text_fast(text, delay=0.01):
    """Faster typewriter for dialogue."""
    for char in text:
        print(char, end='', flush=True)
        time.sleep(delay)
    print()


def dramatic_pause(seconds=1.0):
    """Pause for dramatic effect."""
    time.sleep(seconds)


def suspense_dots(count=3, delay=0.5):
    """Show suspenseful dots."""
    for _ in range(count):
        print(".", end='', flush=True)
        time.sleep(delay)
    print()


# ============================================================================
# DISPLAY ELEMENTS
# ============================================================================

def show_divider(char="-", width=60):
    """Print a divider line."""
    print(char * width)


def show_immersive_header(title, subtitle=None):
    """Print an atmospheric styled header."""
    print()
    print("═" * 60)
    print(f"  ▸ {title}")
    if subtitle:
        print(f"    {subtitle}")
    print("═" * 60)


def flicker_text(text, flickers=2):
    """Simulate flickering display."""
    for _ in range(flickers):
        print(f"\r{text}", end='', flush=True)
        time.sleep(0.1)
        print(f"\r{' ' * len(text)}", end='', flush=True)
        time.sleep(0.05)
    print(f"\r{text}")


