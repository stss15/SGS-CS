class GameState:
    """Tracks mutable game state (unlocked doors, taken items, etc.)."""
    
    def __init__(self):
        self.current_room = "airlock"
        self.visited_rooms = set()
        self.taken_items = set()  # Items removed from world
        self.unlocked_doors = set()  # Door IDs that are unlocked
        self.opened_containers = set()  # Container IDs that are opened
        self.triggered_encounters = set()  # Encounters that have triggered
        self.npc_dialogue_state = {}  # NPC ID -> dialogue trigger state
        self.puzzle_solved = set()  # Puzzle IDs that are solved
        self.game_complete = False
    
    def to_dict(self) -> dict:
        """Convert state to serialisable dict."""
        return {
            "current_room": self.current_room,
            "visited_rooms": list(self.visited_rooms),
            "taken_items": list(self.taken_items),
            "unlocked_doors": list(self.unlocked_doors),
            "opened_containers": list(self.opened_containers),
            "triggered_encounters": list(self.triggered_encounters),
            "npc_dialogue_state": self.npc_dialogue_state,
            "puzzle_solved": list(self.puzzle_solved),
            "game_complete": self.game_complete
        }
    
    @classmethod
    def from_dict(cls, data: dict) -> "GameState":
        """Reconstruct state from dict."""
        state = cls()
        state.current_room = data.get("current_room", "airlock")
        state.visited_rooms = set(data.get("visited_rooms", []))
        state.taken_items = set(data.get("taken_items", []))
        state.unlocked_doors = set(data.get("unlocked_doors", []))
        state.opened_containers = set(data.get("opened_containers", []))
        state.triggered_encounters = set(data.get("triggered_encounters", []))
        state.npc_dialogue_state = data.get("npc_dialogue_state", {})
        state.puzzle_solved = set(data.get("puzzle_solved", []))
        state.game_complete = data.get("game_complete", False)
        return state


