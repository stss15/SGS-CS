    def _game_loop(self):
        """Main game loop."""
        while self.running:
            if self.state.game_complete:
                self._show_victory()
                break
            
            print()
            raw = input("> ").strip()
            if not raw:
                continue
            
            parsed = self.parser.parse(raw)
            self._handle_command(parsed)
    
    def _handle_command(self, parsed: dict):
        """Route a parsed command to the appropriate handler."""
        cmd = parsed["command"]
        args = parsed["args"]
        
        if cmd is None:
            return
        
        if cmd == "unknown":
            self._unknown_command(args)
        elif cmd == "look":
            self._look_handler(args)
        elif cmd in ("north", "south", "east", "west", "up", "down"):
            self._move_handler([cmd])
        elif cmd == "move":
            self._move_handler(args)
        elif cmd == "take":
            self._take_handler(args)
        elif cmd == "inventory":
            self._inventory_handler(args)
        elif cmd == "use":
            self._use_handler(args)
        elif cmd == "talk":
            self._talk_handler(args)
        elif cmd == "status":
            self._status_handler(args)
        elif cmd == "save":
            self._save_handler(args)
        elif cmd == "load":
            self._load_handler(args)
        elif cmd == "help":
            self._help_handler(args)
        elif cmd == "quit":
            self._quit_handler(args)
        else:
            self._unknown_command([cmd] + args)
    
    def _unknown_command(self, args: list):
        """Handle unknown commands."""
        if args:
            print(f"I don't understand '{' '.join(args)}'. Type 'help' for commands.")
        else:
            print("I didn't catch that. Type 'help' for commands.")
    
    def _describe_room(self):
        """Describe the current room."""
        room = self.world.get_room(self.state.current_room)
        if not room:
            print("Error: Room not found.")
            return
        
        first_visit = self.state.current_room not in self.state.visited_rooms
        
        print()
        print("═" * 60)
        print(f"  ▸ {room['name'].upper()}")
        print("═" * 60)
        
        desc = room.get("description_first", room.get("description", "You are here."))
        if not first_visit and "description_revisit" in room:
            desc = room.get("description_revisit")
        
        # Typewriter effect for room descriptions
        if first_visit:
            type_text(desc)
        else:
            print(desc)
        
        self.state.visited_rooms.add(self.state.current_room)
        
        # Occasional ambient atmosphere
        room_atmosphere(room['name'], first_visit)
        
        # Show items (not taken)
        self._show_room_items()
        
        # Show NPCs
        self._show_room_npcs()
        
        # Show exits
        self._show_exits()
    
    def _show_room_items(self):
        """Show items in the current room."""
        room = self.world.get_room(self.state.current_room)
        if not room:
            return
        
        # Regular items
        for item_id in room.get("items", []):
            if item_id not in self.state.taken_items:
                item = self.world.get_item(item_id)
                if item:
                    desc = item.get('description_room')
                    if not desc:
                        desc = "You see a " + item.get('name', 'something') + "."
                    print("\n" + desc)
        
        # Hidden items (reveal if condition met)
        for item_id, hint in room.get("hidden_items", {}).items():
            if item_id not in self.state.taken_items:
                # Show hint for hidden items
                print(f"\n{hint}")
        
        # Container contents
        if "chest" in room:
            chest = room["chest"]
            if chest["id"] not in self.state.opened_containers:
                if chest.get("locked", False):
                    print(f"\nA heavy chest sits in the corner, its lock jammed shut.")
                else:
                    print(f"\nAn open chest reveals its contents.")
            else:
                # Show chest contents if not taken
                for item_id in chest.get("contains", []):
                    if item_id not in self.state.taken_items:
                        item = self.world.get_item(item_id)
                        if item:
                            print(f"\nIn the chest: {item.get('description_room')}")
    
    def _show_room_npcs(self):
        """Show NPCs in the current room."""
        room = self.world.get_room(self.state.current_room)
        if not room:
            return
        
        for npc_id in room.get("npcs", []):
            npc = self.world.get_npc(npc_id)
            if npc:
                print(f"\n{npc.get('description')}")
    
    def _show_exits(self):
        """Show available exits."""
        room = self.world.get_room(self.state.current_room)
        if not room:
            return
        
        exits = room.get("exits", {})
        locked = room.get("locked_exits", {})
        
        if exits:
            exit_strs = []
            for direction, dest in exits.items():
                if direction in locked and locked[direction] not in self.state.unlocked_doors:
                    exit_strs.append(f"{direction} (locked)")
                else:
                    exit_strs.append(direction)
            print(f"\nExits: {', '.join(exit_strs)}")
    
    def _look_handler(self, args: list):
        """Handle look command."""
        if not args:
            self._describe_room()
        else:
            target = " ".join(args)
            self._examine(target)
    
    def _examine(self, target: str):
        """Examine a specific thing."""
        target = target.lower()
        
        # Check inventory items
        for item_id in self.player.inventory.list_items():
            item = self.world.get_item(item_id)
            if item and (target in item_id.lower() or target in item.get("name", "").lower()):
                desc = item.get("description_examine")
                if not desc:
                    desc = "It's a " + item.get('name', 'something') + "."
                print(desc)
                return
        
        # Check room items
        room = self.world.get_room(self.state.current_room)
        if room:
            for item_id in room.get("items", []) + list(room.get("hidden_items", {}).keys()):
                if item_id not in self.state.taken_items:
                    item = self.world.get_item(item_id)
                    if item and (target in item_id.lower() or target in item.get("name", "").lower()):
                        desc = item.get("description_examine")
                        if not desc:
                            desc = "It's a " + item.get('name', 'something') + "."
                        print(desc)
                        return
            
            # Check NPCs
            for npc_id in room.get("npcs", []):
                npc = self.world.get_npc(npc_id)
                if npc and (target in npc_id.lower() or target in npc.get("name", "").lower()):
                    print(npc.get("description", f"You see {npc['name']}."))
                    return
        
        print(f"You don't see '{target}' here.")
    
    def _move_handler(self, args: list):
        """Handle movement."""
        if not args:
            print("Move where? (north, south, east, west, up, down)")
            return
        
        direction = self.parser.normalise_direction(args[0])
        room = self.world.get_room(self.state.current_room)
        
        if not room:
            return
        
        exits = room.get("exits", {})
        locked_exits = room.get("locked_exits", {})
        
        if direction not in exits:
            print("You can't go that way.")
            return
        
        # Check if locked
        if direction in locked_exits:
            door_id = locked_exits[direction]
            if door_id not in self.state.unlocked_doors:
                print("That way is locked.")
                return
        
        # Check for exit encounter trigger
        encounter_id = room.get("encounter_on_first_exit")
        if encounter_id and encounter_id not in self.state.triggered_encounters:
            self.state.triggered_encounters.add(encounter_id)
            result = self.encounters.run_encounter(encounter_id, self.player)
            if result == "defeat":
                self._handle_death()
                return
            elif result == "escaped":
                print("You retreat back into the room.")
                return
        
        # Move to new room
        movement_narration(direction)
        new_room_id = exits[direction]
        self.state.current_room = new_room_id
        
        # Check for entry encounter
        new_room = self.world.get_room(new_room_id)
        if new_room:
            encounter_id = new_room.get("encounter_on_first_entry")
            if encounter_id and encounter_id not in self.state.triggered_encounters:
                # Show room first
                self._describe_room()
                # Then trigger encounter
                self.state.triggered_encounters.add(encounter_id)
                result = self.encounters.run_encounter(encounter_id, self.player)
                if result == "defeat":
                    self._handle_death()
                    return
                return
        
        self._describe_room()
    
    def _take_handler(self, args: list):
        """Handle taking items."""
        if not args:
            print("Take what?")
            return
        
        target = " ".join(args).lower()
        room = self.world.get_room(self.state.current_room)
        
        if not room:
            return
        
        # Check regular items
        for item_id in room.get("items", []):
            if item_id not in self.state.taken_items:
                item = self.world.get_item(item_id)
                if item and (target in item_id.lower() or target in item.get("name", "").lower()):
                    if self.player.inventory.add(item_id):
                        self.state.taken_items.add(item_id)
                        item_pickup_narration(item['name'])
                    else:
                        print("Your inventory is full!")
                    return
        
        # Check hidden items
        for item_id in room.get("hidden_items", {}).keys():
            if item_id not in self.state.taken_items:
                item = self.world.get_item(item_id)
                if item and (target in item_id.lower() or target in item.get("name", "").lower()):
                    if self.player.inventory.add(item_id):
                        self.state.taken_items.add(item_id)
                        print(f"You find and take the {item['name']}!")
                    else:
                        print("Your inventory is full!")
                    return
        
        # Check chest contents
        if "chest" in room:
            chest = room["chest"]
            if chest["id"] in self.state.opened_containers:
                for item_id in chest.get("contains", []):
                    if item_id not in self.state.taken_items:
                        item = self.world.get_item(item_id)
                        if item and (target in item_id.lower() or target in item.get("name", "").lower()):
                            if self.player.inventory.add(item_id):
                                self.state.taken_items.add(item_id)
                                print(f"You take the {item['name']} from the chest.")
                            else:
                                print("Your inventory is full!")
                            return
        
        print(f"You don't see '{target}' to take.")
    
    def _inventory_handler(self, args: list):
        """Show inventory."""
        items = self.player.inventory.list_items()
        
        print("\n--- INVENTORY ---")
        if not items:
            print("  (empty)")
        else:
            for item_id in items:
                item = self.world.get_item(item_id)
                if item:
                    print(f"  • {item.get('description_inventory', item['name'])}")
        print(f"\nCapacity: {self.player.inventory.count()}/{self.player.inventory.MAX_CAPACITY}")
    
    def _use_handler(self, args: list):
        """Handle using items."""
        if not args:
            print("Use what?")
            return
        
        item_str, target_str = self.parser.parse_use_command(args)
        
        if not item_str:
            print("Use what?")
            return
        
        # Find the item in inventory
        found_item_id = None
        for item_id in self.player.inventory.list_items():
            item = self.world.get_item(item_id)
            if item and (item_str in item_id.lower() or item_str in item.get("name", "").lower()):
                found_item_id = item_id
                break
        
        if not found_item_id:
            print(f"You don't have '{item_str}'.")
            return
        
        # Get item data
        item = self.world.get_item(found_item_id)
        
        # Call student's use_item method
        try:
            result = self.player.use_item(found_item_id, target_str)
            print(result)
        except Exception as e:
            print(f"Error using item: {e}")
            return
        
        # Handle special effects
        self._process_item_effect(found_item_id, target_str, item)
    
    def _process_item_effect(self, item_id: str, target: str, item: dict):
        """Process special item effects."""
        effects = item.get("effects", {})
        
        # Unlock doors
        for door_id, effect in effects.items():
            if effect == "unlock":
                self.state.unlocked_doors.add(door_id)
                print(f"*Click* The lock disengages.")
        
        # Open containers
        room = self.world.get_room(self.state.current_room)
        if room and "chest" in room:
            chest = room["chest"]
            if item_id == chest.get("requires"):
                self.state.opened_containers.add(chest["id"])
                print("The chest opens, revealing its contents!")
                for contained_id in chest.get("contains", []):
                    contained = self.world.get_item(contained_id)
                    if contained:
                        print(f"  → {contained['name']}")
        
        # Handle healing
        if item.get("consumable"):
            if item.get("heal_amount"):
                self.player.heal(item["heal_amount"])
                self.player.inventory.consume(item_id)
        
        # Handle victory item
        if item.get("is_victory_item"):
            self.state.game_complete = True
    
    def _talk_handler(self, args: list):
        """Handle talking to NPCs."""
        room = self.world.get_room(self.state.current_room)
        if not room:
            return
        
        npc_ids = room.get("npcs", [])
        if not npc_ids:
            print("There's no one here to talk to.")
            return
        
        # Find NPC
        target = " ".join(args).lower() if args else ""
        
        found_npc = None
        for npc_id in npc_ids:
            npc = self.world.get_npc(npc_id)
            if npc:
                if not target or target in npc_id.lower() or target in npc.get("name", "").lower():
                    found_npc = npc
                    break
        
        if not found_npc:
            print(f"You don't see '{target}' to talk to.")
            return
        
        # Get dialogue state
        npc_id = found_npc["id"]
        dialogue_trigger = self.state.npc_dialogue_state.get(npc_id, "first_talk")
        
        # Find matching dialogue
        dialogue_data = None
        for dialogue in found_npc.get("dialogue", []):
            if dialogue.get("trigger") == dialogue_trigger:
                dialogue_data = dialogue
                break
        
        # Fallback to first_talk
        if not dialogue_data:
            for dialogue in found_npc.get("dialogue", []):
                if dialogue.get("trigger") == "first_talk":
                    dialogue_data = dialogue
                    break
        
        if not dialogue_data:
            print(f"{found_npc['name']} has nothing to say.")
            return
        
        # Show dialogue with immersion
        npc_greeting(found_npc['name'])
        print()
        type_text(dialogue_data.get("text", "..."))
        
        # Handle options
        options = dialogue_data.get("options")
        responses = dialogue_data.get("responses")
        
        if options and responses:
            print("\nYou can ask about:")
            for i, opt in enumerate(options):
                print(f"  {i + 1}. {opt}")
            
            # Get player choice via student method
            try:
                choice = self.player.respond_to_npc(options)
                if isinstance(choice, int) and 0 <= choice < len(responses):
                    print()
                    print(responses[choice])
            except Exception as e:
                print(f"(Error in respond_to_npc: {e})")
        
        # Update dialogue state
        self.state.npc_dialogue_state[npc_id] = "after_first"
    
    def _status_handler(self, args: list):
        """Show player status."""
        print(self.player.get_status())
    
    def _save_handler(self, args: list):
        """Save the game."""
        if self.saves.save_game(self.player, self.state.to_dict()):
            print("Game saved.")
        else:
            print("Failed to save game.")
    
    def _load_handler(self, args: list):
        """Load a saved game."""
        self._load_game()
    
    def _load_game(self):
        """Load game implementation."""
        player, engine_state = self.saves.load_game(self.player_class or self._get_player_class())
        
        if player and engine_state:
            self.player = player
            self.state = GameState.from_dict(engine_state)
            print("Game loaded.")
            self._describe_room()
        else:
            print("Could not load game.")
    
    def _get_player_class(self):
        """Get the appropriate player class for loading."""
        try:
            from student.player_types import Brute
            return Brute  # Default to Brute if unknown
        except ImportError:
            return None
    
